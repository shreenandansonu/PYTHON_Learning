#creating the database and is executed only once via runing this file
#it creates a database file named bankdatabase.db in the Indian Bank folder
def create_database():
    with sq3.connect('./Indian Bank/bankdatabase.db') as con:
        cur = con.cursor()

        cur.execute('''CREATE TABLE IF NOT EXISTS bankaccounts(
                    
                    name TEXT NOT NULL,
                    fname TEXT NOT NULL,
                    dob TEXT NOT NULL,
                    balance REAL NOT NULL,
                    password TEXT NOT NULL
                    )''')
        con.commit()


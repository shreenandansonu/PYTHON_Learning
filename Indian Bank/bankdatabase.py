#this allows you to login to your account
#it returns the rowid and all the values of the account if successful, else returns False

def login(name:str,password:str):
    with sq3.connect('./Indian Bank/bankdatabase.db') as con:
        cur=con.cursor()
        cur.execute('''SELECT rowid,* FROM bankaccounts WHERE name=? AND password=?''',(name,password))
        value=cur.fetchall()
        if value:
            return value
        else:
            return False
    
def updating_database(rowid:int,placevalue: str,value):
    valid_columns=['name','fname','dob','balance','password']
    if placevalue not in valid_columns:
        raise ValueError(f"{placevalue}is not a valid column name.")

    with sq3.connect('./Indian Bank/bankdatabase.db') as con:
        cur = con.cursor()
